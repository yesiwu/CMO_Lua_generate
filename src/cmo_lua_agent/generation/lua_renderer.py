def _build_context(plan: ExecutionPlan) -> _RenderContext:
    unit_names: dict[str, str] = {}
    unit_sides: dict[str, str] = {}
    routes: dict[str, dict[str, Any]] = {}
    air_targets: dict[str, dict[str, Any]] = {}

    for operation in plan.operations:
        parameters = operation.parameters
        if operation.primitive_type in {"ensure_ship", "ensure_aircraft"}:
            unit_id = str(parameters["unit_id"])
            unit_names[unit_id] = str(parameters["name"])
            unit_sides[unit_id] = str(parameters["side_id"])
        elif operation.primitive_type == "set_aircraft_route":
            route = parameters["route"]
            if len(route) < 2:
                continue
            routes[str(parameters["sortie_id"])] = {
                "mid_lat": route[0]["latitude"],
                "mid_lon": route[0]["longitude"],
                "app_lat": route[1]["latitude"],
                "app_lon": route[1]["longitude"],
                "altitude_meters": parameters["altitude_meters"],
                "throttle": parameters["throttle"],
                "return_delay_seconds": 600,
            }
        elif operation.primitive_type == "aircraft_attack":
            sortie_id = str(parameters["sortie_id"])
            air_targets[sortie_id] = {
                "target_id": parameters["target_ids"][0],
                "weapon_dbid": parameters["weapon_dbid"],
                "fire_quantity": parameters["fire_quantity"],
            }
            if sortie_id in routes:
                routes[sortie_id]["return_delay_seconds"] = parameters["return_delay_seconds"]
    return _RenderContext(
        unit_names=unit_names,
        unit_sides=unit_sides,
        routes=routes,
        air_targets=air_targets,
    )


def _lua_value(value: Any) -> str:
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, Mapping):
        pairs = [
            f"[{_lua_value(key)}]={_lua_value(item)}"
            for key, item in sorted(value.items())
        ]
        return "{" + ", ".join(pairs) + "}"
    if isinstance(value, (list, tuple)):
        return "{" + ", ".join(_lua_value(item) for item in value) + "}"
    raise TypeError(f"unsupported Lua value: {type(value).__name__}")
